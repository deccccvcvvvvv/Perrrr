#!/usr/bin/env python3
"""Generates app/src/main/cpp/cssdl3_stubs.c for the launcher's SDL3 bridge.

LWJGL resolves every function of an org.lwjgl.sdl binding class when the class initialises, so libcsglfw.so must
export the whole SDL3 API that LWJGL binds, not only what Minecraft calls. Functions implemented by hand in
cssdl3.c / cssdl3_libc.c are skipped. Every other function gets a stub that records "not supported" in SDL_GetError(),
logs once and returns 0 / NULL / false (0.0 for floating-point returns).

Usage: gen_sdl_stubs.py --jar lwjgl-sdl-3.4.3.jar [--repo .]
Writes tools/natives34/sdl3_required.txt (every symbol LWJGL needs, checked by verify) and the stubs source.
"""
import argparse, re, struct, sys, zipfile
from pathlib import Path


def class_strings(data: bytes):
    """Returns the CONSTANT_String values of a class file (the function names given to apiGetFunctionAddress)."""
    if data[:4] != b"\xca\xfe\xba\xbe":
        return []
    count = struct.unpack(">H", data[8:10])[0]
    utf8, strings, i, off = {}, [], 1, 10
    while i < count:
        tag = data[off]
        if tag == 1:
            ln = struct.unpack(">H", data[off + 1:off + 3])[0]
            utf8[i] = data[off + 3:off + 3 + ln].decode("utf-8", "replace"); off += 3 + ln
        elif tag == 8:
            strings.append(struct.unpack(">H", data[off + 1:off + 3])[0]); off += 3
        elif tag in (3, 4, 9, 10, 11, 12, 17, 18):
            off += 5
        elif tag in (5, 6):
            off += 9; i += 1
        elif tag in (7, 16, 19, 20):
            off += 3
        elif tag == 15:
            off += 4
        else:
            raise ValueError(f"unknown constant tag {tag}")
        i += 1
    return [utf8[s] for s in strings if s in utf8]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--jar", required=True)
    ap.add_argument("--repo", default=str(Path(__file__).resolve().parents[2]))
    a = ap.parse_args()
    repo = Path(a.repo)
    cpp = repo / "app/src/main/cpp"

    required = set()
    with zipfile.ZipFile(a.jar) as z:
        for n in z.namelist():
            if n.startswith("org/lwjgl/sdl/") and n.endswith("$Functions.class"):
                required.update(s for s in class_strings(z.read(n)) if re.fullmatch(r"SDL_\w+", s))
    if len(required) < 500:
        sys.exit(f"only {len(required)} SDL functions found in {a.jar}; wrong jar?")

    implemented = set()
    for f in ("cssdl3.c", "cssdl3_libc.c"):
        for m in re.finditer(r"^(?:SDL_EXPORT|E)\s[^\n(]*?\b(SDL_\w+)\(", (cpp / f).read_text(), re.M):
            implemented.add(m.group(1))

    rettypes = {}
    for h in (cpp / "third_party/SDL3/include/SDL3").glob("*.h"):
        for m in re.finditer(r"extern\s+SDL_DECLSPEC\s+(.*?)\s*SDLCALL\s+(SDL_\w+)\s*\(", h.read_text(errors="replace"), re.S):
            rettypes[m.group(2)] = " ".join(m.group(1).split())

    stubs = sorted(required - implemented)
    out = [
        "/* GENERATED by tools/natives34/gen_sdl_stubs.py from lwjgl-sdl 3.4.3 - do not edit.",
        " * SDL3 functions LWJGL binds but the CS Launcher Android bridge (cssdl3.c) does not implement. Each fails cleanly:",
        " * SDL_GetError() names the function, a warning is logged once, and 0 / NULL / false is returned. */",
        "long long cs_sdl_unsupported(const char *name);",
        "#define S(n) __attribute__((visibility(\"default\"))) long long n(void) { return cs_sdl_unsupported(#n); }",
        "#define F(n) __attribute__((visibility(\"default\"))) float n(void) { cs_sdl_unsupported(#n); return 0.0f; }",
        "#define D(n) __attribute__((visibility(\"default\"))) double n(void) { cs_sdl_unsupported(#n); return 0.0; }",
    ]
    for n in stubs:
        rt = rettypes.get(n, "")
        kind = "F" if rt == "float" else "D" if rt == "double" else "S"
        out.append(f"{kind}({n})")
    (cpp / "cssdl3_stubs.c").write_text("\n".join(out) + "\n")
    (repo / "tools/natives34/sdl3_required.txt").write_text("\n".join(sorted(required)) + "\n")
    print(f"required {len(required)}, implemented {len(required & implemented)}, stubs {len(stubs)}, "
          f"extra implemented (not bound by LWJGL) {len(implemented - required)}")
    missing_hdr = [n for n in stubs if n not in rettypes]
    if missing_hdr:
        print(f"note: {len(missing_hdr)} bound functions are not in the vendored headers: {' '.join(missing_hdr[:10])}")


if __name__ == "__main__":
    main()
