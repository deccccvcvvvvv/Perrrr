import java.nio.file.StandardCopyOption

/** Content shipped inside the APK (assets/bundled/<abi>/index.json), generated by the CI natives job. */
@Serializable data class BundledRuntime(val id: String, val major: Int, val version: String, val file: String, val sha256: String, val size: Long, val source: String)
@Serializable data class BundledComponent(val id: String, val version: String, val file: String, val sha256: String, val size: Long)
@Serializable data class BundleIndex(val formatVersion: Int = 1, val abi: String, val runtimes: List<BundledRuntime> = emptyList(), val components: List<BundledComponent> = emptyList())

interface BundleSource {
    /** The index for [abi] or null when nothing is bundled for it. */
    fun index(abi: String): BundleIndex?
    fun open(abi: String, file: String): InputStream
}

/**
 * Installs Java runtimes and native component packs automatically:
 *  1. from the APK when the build bundled them (preferred, works offline);
 *  2. otherwise downloads the Android OpenJDK build for this ABI from the AngelAuraMC release, verified against the
 *     SHA-256 digest GitHub publishes for the asset.
 * Nothing is activated before its checksum matches.
 */
class AutoProvisioner(
    private val dirs: LauncherDirs,
    private val platform: PlatformInfo,
    private val runtimes: RuntimeManager,
    private val components: ComponentManager,
    private val bundle: BundleSource?,
    private val http: HttpTransport?,
    private val downloads: DownloadManager?,
) : Provisioner {
    private val abi get() = platform.arch.androidAbi ?: error("Not an Android platform")
    private val lock = Any()

    /** Majors offered by the Android OpenJDK project. */
    val downloadableMajors = listOf(8, 17, 21, 25)

    /** Smallest supplied major that satisfies [required] (8 stays 8: old Forge/LWJGL setups need exactly Java 8). */
    fun targetMajor(required: Int, offered: List<Int>): Int? = offered.sorted().firstOrNull { it >= required }

    override fun ensureRuntime(major: Int, progress: (String) -> Unit) = synchronized(lock) {
        val installed = runtimes.list().filter { it.isAndroidBuild && it.libjvm() != null }
        val src = bundle
        val idx = src?.index(abi)
        val bundledMajors = idx?.runtimes?.map { it.major }.orEmpty()
        val target = targetMajor(major, (bundledMajors + downloadableMajors).distinct()) ?: return@synchronized
        if (installed.any { it.major == target }) return@synchronized
        val b = idx?.runtimes?.filter { it.major == target }?.maxByOrNull { it.version }
        val staging = dirs.runtimeRoot.resolve(".incoming"); Files.createDirectories(staging)
        val archive = staging.resolve("jre$target.tar.xz")
        try {
            if (b != null) {
                progress("Preparing Java $target (first launch only)…")
                src!!.open(abi, b.file).use { Files.copy(it, archive, StandardCopyOption.REPLACE_EXISTING) }
                progress("Unpacking Java $target…")
                runtimes.install(archive, "jre$target", b.sha256, "bundled", androidBuild = true)
            } else {
                val (url, sha) = resolveDownload(target)
                progress("Downloading Java $target…")
                val dm = downloads ?: error("Downloads unavailable")
                val r = runBlocking { dm.downloadOne(DownloadTask(url, archive, Integrity(sha256 = sha), "Java $target runtime")) }
                if (r.error != null) error("Java $target download failed: ${r.error}")
                progress("Unpacking Java $target…")
                runtimes.install(archive, "jre$target", sha, "downloaded", androidBuild = true)
            }
            CsLog.i("Provision", "Installed Java $target for $abi from ${if (b != null) "the APK" else "AngelAuraMC"}")
        } finally { Files.deleteIfExists(archive) }
    }

    /** Asset name used by the Android OpenJDK releases. */
    fun releaseArch(): String = when (abi) { "arm64-v8a" -> "arm64"; "armeabi-v7a" -> "arm"; "x86_64" -> "x86_64"; "x86" -> "x86"; else -> error("Unsupported ABI $abi") }

    private fun resolveDownload(major: Int): Pair<String, String> {
        val h = http ?: error("No network transport")
        val name = "jre$major-android-${releaseArch()}.tar.xz"
        val json = CsJson.parseToJsonElement(h.getText("https://api.github.com/repos/AngelAuraMC/angelauramc-openjdk-build/releases/tags/download_jre$major",
            mapOf("Accept" to "application/vnd.github+json"))).jsonObject
        val asset = json["assets"]?.jsonArray?.map { it.jsonObject }?.firstOrNull { it["name"]?.jsonPrimitive?.content == name }
            ?: error("No Java $major build is published for ${releaseArch()}")
        val digest = asset["digest"]?.jsonPrimitive?.content?.removePrefix("sha256:") ?: error("Java $major build has no published checksum; refusing to install it")
        return asset["browser_download_url"]!!.jsonPrimitive.content to digest
    }

    override fun ensureComponents(progress: (String) -> Unit) = synchronized(lock) {
        val src = bundle ?: return@synchronized
        val idx = src.index(abi) ?: return@synchronized
        val installed = components.list().associateBy { it.manifest.id }
        for (c in idx.components) {
            val have = installed[c.id]
            if (have != null && have.manifest.version == c.version && components.verify(have).isEmpty()) continue
            progress("Installing ${c.id} ${c.version}…")
            val staging = dirs.componentRoot.resolve(".incoming"); Files.createDirectories(staging)
            val f = staging.resolve(c.id + ".zip")
            try {
                src.open(abi, c.file).use { Files.copy(it, f, StandardCopyOption.REPLACE_EXISTING) }
                val actual = Hashing.sha256(f)
                require(actual.equals(c.sha256, true)) { "Bundled ${c.id} is corrupt (checksum mismatch)" }
                components.import(f, abi)
                CsLog.i("Provision", "Installed bundled component ${c.id} ${c.version}")
            } finally { Files.deleteIfExists(f) }
        }
    }

    /** What the APK provides for this device, for the settings screen. */
    fun describeBundle(): String {
        val idx = bundle?.index(abi) ?: return "Nothing bundled for $abi; Java is downloaded automatically when needed"
        return "Bundled for $abi: " + (idx.runtimes.map { "Java ${it.major}" } + idx.components.map { it.id }).joinToString()
    }

    companion object {
        fun parseIndex(text: String): BundleIndex = CsJson.decodeFromString(BundleIndex.serializer(), text)
    }
}
